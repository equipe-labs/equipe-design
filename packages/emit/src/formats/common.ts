import { ROLES, type RoleName } from '@equipe-design/remix';
import type { Resolved, Rgba, ShadowV, Token, Typo } from '../tokens.ts';

export interface EmitOptions {
  /** CSS variable prefix: `eq` gives `--eq-color-text`. */
  prefix?: string;
  /** Type-name prefix in Swift and Kotlin (default: the CSS prefix in PascalCase). */
  typePrefix?: string;
  /** Kotlin package. */
  kotlinPackage?: string;
  /** shadcn colour syntax: `oklch(1 0 0)` (current shadcn) or `0 0% 100%` for `hsl(var(--x))` (older). */
  shadcnFormat?: 'oklch' | 'hsl';
  /** Strings that must not appear in a token name or file name (source site labels). */
  forbidden?: string[];
}

export const HEADER = 'Generated by equipe-design emit — do not edit by hand; change the tokens and emit again.';
export const trim = (n: number) => String(Math.round(n * 1000) / 1000);
export const camel = (s: string) => s.replace(/[-_.\s]+(\w)/g, (_, c: string) => c.toUpperCase());
export const pascal = (s: string) => { const c = camel(s); return c.charAt(0).toUpperCase() + c.slice(1); };
export const kebab = (path: string[]) => path.join('-');
export const hexA = (c: Rgba) => (c.a < 1 ? c.hex + Math.round(c.a * 255).toString(16).padStart(2, '0') : c.hex);

export interface View {
  light: Token[];
  dark: Token[] | null;
  find(list: Token[], name: string): Token | undefined;
  colors(mode: 'light' | 'dark'): Record<RoleName, Rgba> | null;
  hasDark: boolean;
  /** tokens that are not colours, from the light tree, without the raw palette and component group */
  shape: Token[];
  raw: Token[];
}

export function view(r: Resolved): View {
  const find = (list: Token[], name: string) => list.find((t) => t.name === name);
  const colors = (mode: 'light' | 'dark') => {
    const list = mode === 'light' ? r.light : r.dark;
    if (!list) return null;
    const out = {} as Record<RoleName, Rgba>;
    for (const role of ROLES) {
      const t = find(list, `color.${role}`);
      if (!t) throw new Error(`color.${role} is missing from the ${mode} tokens`);
      out[role] = t.value as Rgba;
    }
    return out;
  };
  return {
    light: r.light,
    dark: r.dark,
    find,
    colors,
    hasDark: !!r.dark,
    raw: r.light.filter((t) => t.name.startsWith('color.raw.')),
    shape: r.light.filter((t) => t.type !== 'color' && !t.name.startsWith('component.')),
  };
}

export const typo = (t: Token) => t.value as Typo;
export const shadows = (t: Token) => t.value as ShadowV[];
export const byPrefix = (list: Token[], p: string) => list.filter((t) => t.name.startsWith(p + '.'));
export const stepOf = (t: Token) => t.path[t.path.length - 1]!;
